import {adapterPath, defaultDiagnosticsRoot} from "../common/project_paths.mjs";
import {readFile, readdir, realpath} from "node:fs/promises";
import path from "node:path";
import {canonicalJson, sha256} from "../common/book_schema.mjs";
import {localJsonPath} from "../runtime/upstream_runtime.mjs";

const NEEDED = ["books.json", "references.jsonl", "source-entities.jsonl", "external-targets.jsonl", "files.jsonl"];

/** Accept an explicit inventory or discover one matching the current stage-3 code. */
export async function loadAssemblyInventory({projectRoot, snapshot, inventoryPath, diagnosticsRoot = defaultDiagnosticsRoot}) {
  async function readReport(directory) {
    const report = JSON.parse(await readFile(path.join(directory, "report.json"), "utf8"));
    if (report.stage !== 3 || report.status !== "PASS" || report.inventory_version !== "0.1.0") throw new Error("Expected a successful stage-3 inventory 0.1.0");
    if (report.upstream.checkout_sha !== snapshot.checkout_sha || report.upstream.gitlink_sha !== snapshot.gitlink_sha || !report.upstream.gitlink_matches_checkout || !report.upstream.tracked_clean) throw new Error("Inventory does not match the clean pinned snapshot");
    const {signature, ...generator} = report.generator;
    if (sha256(canonicalJson(generator)) !== signature) throw new Error("Inventory signature is inconsistent");
    if (!Object.keys(report.adapter_file_sha256 || {}).length || sha256(canonicalJson(report.adapter_file_sha256)) !== generator.source_sha256) throw new Error("Inventory adapter hash map is inconsistent");
    if (generator.node_version !== process.versions.node) throw new Error("Inventory was generated by a different Node.js version; rerun inventory");
    for (const [file, checksum] of Object.entries(report.adapter_file_sha256)) {
      if (sha256(await readFile(adapterPath(projectRoot, file))) !== checksum) throw new Error(`Inventory is stale for ${file}; rerun inventory`);
    }
    return report;
  }
  let directory;
  let report;
  if (inventoryPath) {
    directory = await realpath(inventoryPath.endsWith(".json") ? path.dirname(inventoryPath) : inventoryPath);
    report = await readReport(directory);
  } else {
    const parent = path.join(diagnosticsRoot, snapshot.checkout_sha, "inventory");
    const candidates = [];
    try {
      for (const entry of (await readdir(parent, {withFileTypes: true})).sort((a, b) => a.name.localeCompare(b.name))) {
        if (!entry.isDirectory()) continue;
        const folder = path.join(parent, entry.name);
        try { candidates.push({directory: folder, report: await readReport(folder)}); }
        catch { /* Historical inventories are not eligible inputs. */ }
      }
    } catch (error) { if (error.code !== "ENOENT") throw error; }
    if (candidates.length !== 1) throw new Error(`Expected one current inventory, found ${candidates.length}. Run npm --prefix tools/ingestion run inventory or supply --inventory PATH.`);
    ({directory, report} = candidates[0]);
  }
  const artifacts = {};
  for (const file of NEEDED) {
    const bytes = await readFile(path.join(directory, file));
    if (sha256(bytes) !== report.artifacts[file]?.file_sha256) throw new Error(`Inventory integrity check failed: ${file}`);
    artifacts[file] = bytes.toString("utf8");
  }
  const lines = file => artifacts[file].split("\n").filter(Boolean).map(line => JSON.parse(line));
  const books = JSON.parse(artifacts["books.json"]).books;
  const references = lines("references.jsonl");
  const records = [...lines("source-entities.jsonl"), ...lines("external-targets.jsonl")];
  const byRecord = new Map(records.map(record => [record.record_id, record]));
  const byEntity = new Map();
  for (const record of records) {
    if (!record.identity || ["foundry_overlay", "book_tree", "book_catalog"].includes(record.role)) continue;
    if (!byEntity.has(record.identity.entity_id)) byEntity.set(record.identity.entity_id, []);
    byEntity.get(record.identity.entity_id).push(record);
  }
  const inputFiles = new Map(lines("files.jsonl").map(file => [file.file, file]));
  const rawCache = new Map();
  async function readSource(file) {
    const relative = localJsonPath(snapshot.upstream, file);
    if (!rawCache.has(relative)) rawCache.set(relative, (async () => {
      const bytes = await readFile(path.join(snapshot.upstream, relative));
      if (sha256(bytes) !== inputFiles.get(relative)?.file_sha256) throw new Error(`Source differs from inventory: ${relative}`);
      return JSON.parse(bytes.toString("utf8").replace(/^\uFEFF/, ""));
    })());
    return rawCache.get(relative);
  }
  return {directory, report, books, references, byRecord, byEntity, inputFiles, readSource};
}
